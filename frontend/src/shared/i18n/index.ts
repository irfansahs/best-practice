export async function initI18n() {
  await i18n
    .use(DbBackend)
    .use(initReactI18next)
    .init({
      lng: localStorage.getItem('culture') ?? 'en',
      fallbackLng: 'en',
      interpolation: { escapeValue: false },
      resources: fallbackResources,
      partialBundledLanguages: true,
    });

  return i18n;
}

